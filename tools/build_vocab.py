#!/usr/bin/env python3
"""Wrap the original vocabulary page (content/vocab/source.html) into app/vocab.js.

The original script runs unchanged inside VocabApp.create(mount, storage, hooks). Only these seams change:
  - `app` is the element the coach gives it (instead of #app),
  - `localStorage` is the coach's Sync store (claude.ai storage shared across devices),
  - alert/confirm/prompt are in-page (the claude.ai viewer blocks browser dialogs),
  - content/vocab/patch.js is inserted right before the original start-up calls
    (30-word review sets, resume, and the coach's own home screen).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "content" / "vocab" / "source.html"
PATCH = ROOT / "content" / "vocab" / "patch.js"
OUT = ROOT / "app" / "vocab.js"

INIT = "loadState();\nloadMeta();\nloadAudioSetting();\nmigrateTypedToGlobal();\nrenderHome();"


def replace_once(text, old, new):
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"build_vocab: expected exactly one match for {old[:60]!r}, found {n}")
    return text.replace(old, new)


def build():
    html = SRC.read_text(encoding="utf-8")
    scripts = re.findall(r"<script>([\s\S]*?)</script>", html)
    if len(scripts) != 1:
        raise SystemExit("build_vocab: expected one inline <script> in source.html")
    js = scripts[0]
    js = replace_once(js, "const app = document.getElementById('app');", "const app = __mount;")
    js = replace_once(js, INIT, PATCH.read_text(encoding="utf-8") + "\n" + INIT + "\nreturn __api;")
    out = (
        "// Generated by tools/build_vocab.py from content/vocab/source.html + content/vocab/patch.js — do not edit.\n"
        "window.VocabApp = { create(__mount, __storage, __hooks) {\n"
        "const localStorage = __storage;\n"
        "const alert = msg => __hooks.toast(String(msg));\n"
        "const confirm = () => false;\n"
        "const prompt = () => null;\n"
        + js + "\n} };\n"
    )
    OUT.write_text(out, encoding="utf-8")
    return len(out)


if __name__ == "__main__":
    print(f"app/vocab.js: {build() // 1024} KB")
